def generate_pdf_from_html(html_content, output_path=None, options=None):
    """Generate PDF from HTML content using WeasyPrint"""
    default_options = {
        'format': 'A4',
        'margin': '1in',
        'enable_hinting': True
    }
    
    if options:
        default_options.update(options)
    
    try:
        # Create font configuration for better rendering
        font_config = FontConfiguration()
        
        # Create WeasyPrint HTML object
        html_doc = HTML(string=html_content)
        
        # Basic CSS for better PDF formatting
        base_css = CSS(string='''
            @page {
                size: A4;
                margin: 1in;
                @top-right {
                    content: "Page " counter(page) " of " counter(pages);
                    font-size: 10px;
                }
                @top-left {
                    content: "Ghostline Report";
                    font-size: 10px;
                }
            }
            body {
                font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
                font-size: 12px;
                line-height: 1.4;
            }
            .page-break { page-break-before: always; }
        ''')
        
        # Generate PDF
        if output_path:
            html_doc.write_pdf(output_path, stylesheets=[base_css], font_config=font_config)
            with open(output_path, 'rb') as f:
                pdf_bytes = f.read()
        else:
            pdf_bytes = html_doc.write_pdf(stylesheets=[base_css], font_config=font_config)
        
        return pdf_bytes
        
    except Exception as e:
        current_app.logger.error(f"PDF generation failed: {e}")
        raise

def generate_project_report(project_name, date_range_days=30):
    """Generate comprehensive project report"""
    try:
        # Load conversation data
        conversations = load_conversation_enhanced(project_name, limit=100)
        
        # Calculate stats
        total_conversations = len(conversations)
        total_messages = sum(len(turn.get('responses', {})) + 1 for turn in conversations)
        
        # Filter by date range if conversations have timestamps
        cutoff_date = datetime.now() - timedelta(days=date_range_days)
        recent_conversations = conversations  # TODO: Add date filtering when timestamps available
        
        stats = [
            {'value': total_conversations, 'label': 'Total Conversations'},
            {'value': total_messages, 'label': 'Total Messages'},
            {'value': f'{date_range_days} days', 'label': 'Report Period'},
            {'value': len(recent_conversations), 'label': 'Recent Activity'}
        ]
        
        # Render HTML
        html_content = render_template_string(
            REPORT_TEMPLATE,
            title=f"{project_name} Project Report",
            subtitle=f"Intelligence Summary for {date_range_days}-day period",
            report_type="Project Report",
            date=datetime.now().strftime("%Y-%m-%d"),
            conversations=conversations[-20:],  # Last 20 conversations
            stats=stats,
            generation_date=datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        )
        
        return html_content
        
    except Exception as e:
        current_app.logger.error(f"Report generation failed for {project_name}: {e}")
        raise

async def generate_project_pdf(project_name, date_range_days=30, output_path=None):
    """Generate project report as PDF"""
    try:
        html_content = generate_project_report(project_name, date_range_days)
        
        if not output_path:
            safe_name = safe_filename(f"{project_name}_report_{datetime.now().strftime('%Y%m%d')}")
            output_path = f"/tmp/{safe_name}.pdf"
        
        pdf_bytes = await generate_pdf_from_html(html_content, output_path)
        return pdf_bytes, output_path
        
    except Exception as e:
        current_app.logger.error(f"PDF generation failed for {project_name}: {e}")
        raise

def generate_daily_briefing_report(date=None):
    """Generate daily intelligence briefing report"""
    if not date:
        date = datetime.now().date()
    
    try:
        # Get database stats for the day
        stats = []
        
        with get_db_connection() as conn:
            if conn:
                cursor = conn.cursor()
                
                # Count conversations from today
                cursor.execute('''
                    SELECT COUNT(*) FROM chat_threads 
                    WHERE DATE(created_at) = %s
                ''', (date,))
                daily_conversations = cursor.fetchone()[0]
                
                # Count total messages
                cursor.execute('''
                    SELECT COUNT(*) FROM chat_threads
                ''')
                total_conversations = cursor.fetchone()[0]
                
                stats = [
                    {'value': daily_conversations, 'label': 'Today\'s Conversations'},
                    {'value': total_conversations, 'label': 'Total Conversations'},
                    {'value': date.strftime('%A'), 'label': 'Day of Week'}
                ]
        
        # Render HTML
        html_content = render_template_string(
            REPORT_TEMPLATE,
            title="Daily Intelligence Briefing",
            subtitle=f"Activity Summary for {date.strftime('%B %d, %Y')}",
            report_type="Daily Briefing",
            date=date.strftime("%Y-%m-%d"),
            conversations=[],  # Could add recent conversations here
            stats=stats,
            generation_date=datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        )
        
        return html_content
        
    except Exception as e:
        current_app.logger.error(f"Daily briefing generation failed for {date}: {e}")
        raise

