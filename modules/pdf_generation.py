# Sync wrapper functions for Flask routes
def sync_generate_project_pdf(project_name, date_range_days=30, output_path=None):
    """Synchronous wrapper for project PDF generation"""
    try:
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        return loop.run_until_complete(
            generate_project_pdf(project_name, date_range_days, output_path)
        )
    finally:
        loop.close()

